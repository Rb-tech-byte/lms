function outlms_get_instructor_store() {
    $path = outlms_get_instructor_store_path();
    if (!file_exists($path)) {
        $init = outlms_get_initial_instructor_data();
        file_put_contents($path, json_encode($init, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES));
        return $init;
    }
    $raw = @file_get_contents($path);
    $data = json_decode($raw, true);
    if (!is_array($data) || empty($data['courses'])) {
        $init = outlms_get_initial_instructor_data();
        file_put_contents($path, json_encode($init, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES));
        return $init;
    }
    return $data;
}

function outlms_save_instructor_store($data) {
    $path = outlms_get_instructor_store_path();
    file_put_contents($path, json_encode($data, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES));
}
